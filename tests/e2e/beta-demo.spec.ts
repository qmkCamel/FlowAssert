import { copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import { pathToFileURL } from 'node:url'
import { test, expect } from '@playwright/test'
import sharp from 'sharp'

let demo: string, root: string
test.beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), 'mobile-mirror-offline-demo-'))
  await copyFile(resolve('docs/communications/mobile-mirror-demo.html'), join(root, 'demo.html'))
  demo = pathToFileURL(join(root, 'demo.html')).href
})
test.afterEach(async () => { await rm(root, { recursive: true, force: true }) })
test.use({ viewport: { width: 1280, height: 900 }, video: { mode: 'on', size: { width: 1280, height: 900 } } })

test('Recorded history loads recorded PNGs into the shared demo without inventing missing evidence', async ({ page }, info) => {
  // Small test fixtures exercise playback; these are never physical acceptance evidence.
  await mkdir(join(root, 'local-case-assets/success'), { recursive: true })
  await mkdir(join(root, 'local-case-assets/failure'), { recursive: true })
  const png = await sharp({ create: { width: 108, height: 240, channels: 3, background: '#663322' } }).png().toBuffer()
  await writeFile(join(root, 'local-case-assets/success/step-1.png'), png)
  await writeFile(join(root, 'local-case-assets/failure/step-1.png'), png)
  const step = { index: 1, label: '真实步骤测试夹具', kind: 'assertVisible', status: 'passed', message: 'Recorded result', evidence: [{ name: 'step-1.png', bytes: png.length, sha256: 'fixture-only' }], captureStartedAt: '2026-10-08T08:00:00Z' }
  const run = { id: 'fixture-record', startedAt: step.captureStartedAt, yaml: 'test fixture only', steps: [step, { ...step, index: 2, label: '截图缺失夹具', evidence: [{ name: 'missing.png' }] }] }
  await writeFile(join(root, 'local-case-assets/cases.js'), 'window.physicalCases = ' + JSON.stringify({ success: run, failure: { ...run, steps: [{ ...step, status: 'failed', error: 'Expected missing text' }] } }))
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(demo)
  await page.locator('#case-recorded').click()
  await expect(page.locator('#case-note')).toContainText('历史截图回放')
  await expect(page.locator('#screen-image')).toHaveAttribute('src', 'local-case-assets/success/step-1.png')
  await expect(page.locator('#evidence')).toContainText('此步骤实际通过')
  await page.locator('[data-tab="tree"]').click()
  await expect(page.locator('#evidence')).toContainText('此步未获得 XML')
  await page.locator('[data-tab="log"]').click()
  await expect(page.locator('#evidence')).toContainText('fixture-record')
  await expect(page.locator('#review')).toBeHidden()
  await page.locator('#run').click()
  await page.locator('#case-basic').click()
  await expect(page.locator('#screen-image')).toBeVisible()
  await expect(page.locator('#progress')).toHaveAttribute('value', '0')
  await page.locator('#case-recorded').click()
  await page.locator('#frame-next').click()
  await expect(page.locator('#frame-empty')).toContainText('截图读取失败')
  await page.locator('#frame-prev').click()
  await expect(page.locator('#screen-image')).toBeVisible()
  await page.locator('#failure').click()
  await expect(page.locator('#evidence')).toContainText('此步骤实际失败')
  await expect(page.locator('#history li')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const screenshot = info.outputPath('recorded-playback-fixture.png')
  await page.locator('#mock-demo').screenshot({ path: screenshot })
  await info.attach('Playback UI test fixture, not device evidence', { path: screenshot, contentType: 'image/png' })
  expect(errors).toEqual([])
})

test('compact case resources download exact YAML without the repeated historical case section', async ({ page }, info) => {
  const requests: string[] = [], errors: string[] = []
  page.on('request', request => requests.push(request.url()))
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(demo)
  await page.locator('#case-recorded').click()
  const real = page.locator('#case-resources')
  await expect(real).toBeVisible()
  await expect(page.locator('#recorded-case')).toHaveCount(0)
  await expect(page.getByText('历史正例：21/21 通过 · 87.102 秒')).toHaveCount(0)
  await expect(real.getByRole('link', { name: '查看使用与验证边界' })).toHaveAttribute('href', 'local-recorded-demo.md')
  await page.locator('#case-yaml > summary').click()
  for (const [kind, file] of [['positive', 'demo.yaml'], ['negative', 'demo-negative.yaml']] as const) {
    const panel = page.locator(`#recorded-${kind}`)
    await panel.locator('summary').click()
    const source = await readFile(resolve('examples/flows', file), 'utf8')
    expect(await panel.locator('pre').textContent()).toBe(source)
    const pending = page.waitForEvent('download')
    await panel.getByRole('button').click()
    const download = await pending
    expect(download.suggestedFilename()).toBe(file)
    expect(await readFile((await download.path())!, 'utf8')).toBe(source)
    await panel.locator('summary').click()
  }
  await expect(page.locator('#history li')).toHaveCount(0)
  await expect(page.locator('#preview-report')).toBeDisabled()
  const desktop = info.outputPath('recorded-case-desktop.png')
  await real.screenshot({ path: desktop })
  await info.attach('real case source summary desktop, no phone image', { path: desktop, contentType: 'image/png' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const narrow = info.outputPath('recorded-case-narrow.png')
  await real.screenshot({ path: narrow })
  await info.attach('real case source summary narrow, no phone image', { path: narrow, contentType: 'image/png' })
  expect(requests.filter(url => !url.startsWith('file:') && !url.startsWith('data:') && !url.startsWith('blob:'))).toEqual([])
  expect(errors).toEqual([])
})

test('slow physical asset loading leaves the basic case interactive and does not switch it back', async ({ page }) => {
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/local-case-assets/cases.js', async route => {
    await gate
    await route.fulfill({ contentType: 'text/javascript', body: 'window.physicalCases={success:{startedAt:"fixture",yaml:"fixture",steps:[{label:"fixture",kind:"done",status:"passed",evidence:[]}]}}' })
  })
  await page.goto(demo)
  await page.locator('#case-recorded').click()
  await expect(page.locator('#case-note')).toContainText('正在读取')
  await page.waitForTimeout(400)
  await page.locator('#case-basic').click()
  await page.locator('#run').click()
  release()
  await expect(page.locator('#case-basic')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#progress')).toHaveAttribute('value', '1')
  await page.locator('#run').click()
  await page.locator('#case-recorded').click()
  await expect(page.locator('#steps li')).toHaveCount(1)
})

test('offline beta demo preserves failed runs and downloads the reviewed simulation without private assets', async ({ page }, info) => {
  const requests: string[] = [], errors: string[] = []
  page.on('request', request => requests.push(request.url()))
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(demo)
  await expect(page.locator('#mock-demo')).toBeVisible()
  await expect(page.locator('#rerun')).toBeDisabled()
  await page.locator('#run').click()
  await expect(page.locator('#status')).toContainText('5 个模拟步骤完成')
  await page.locator('#failure').click()
  await page.locator('#run').click()
  await expect(page.locator('#status')).toContainText('第 5 步未执行')
  await expect(page.locator('#evidence')).toContainText('期望「2 actions received」')
  await page.screenshot({ path: 'artifacts/screenshots/beta-demo-failure.png', fullPage: true })
  await info.attach('offline Mock failure', { path: 'artifacts/screenshots/beta-demo-failure.png', contentType: 'image/png' })
  await page.locator('#rerun').click()
  await expect(page.locator('#status')).toContainText('5 个模拟步骤完成')
  const history = page.locator('#history li')
  await expect(history).toHaveCount(3)
  await expect(history.nth(1)).toContainText('MOCK-002 · 失败 · 4/5 步')
  await expect(history.nth(2)).toContainText('复验自 MOCK-002')
  await history.nth(1).getByRole('button').click()
  await expect(page.locator('#evidence')).toContainText('断言失败')
  await page.locator('#preview-report').click()
  await expect(page.locator('#download-report')).toBeDisabled()
  const frozen = await page.locator('#report-frame').getAttribute('srcdoc')
  await page.locator('#report-confirm').check()
  const downloadPromise = page.waitForEvent('download')
  await page.locator('#download-report').click()
  const download = await downloadPromise
  expect(await readFile((await download.path())!, 'utf8')).toBe(frozen)
  expect(frozen).not.toMatch(/<script|https?:|local-case-assets/)
  await expect(page.frameLocator('#report-frame').locator('body')).toContainText('未执行真实测试')
  await page.locator('#review').scrollIntoViewIfNeeded()
  await page.locator('#review').screenshot({ path: 'artifacts/screenshots/beta-demo-review.png' })
  await info.attach('reviewed simulation', { path: 'artifacts/screenshots/beta-demo-review.png', contentType: 'image/png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(async () => (await sharp(await page.locator('#report-frame').screenshot()).stats()).channels[0]!.stdev).toBeGreaterThan(10)
  await page.locator('#review').screenshot({ path: 'artifacts/screenshots/beta-demo-narrow.png' })
  await info.attach('narrow offline demo', { path: 'artifacts/screenshots/beta-demo-narrow.png', contentType: 'image/png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(requests.filter(url => !url.startsWith('file:') && !url.startsWith('data:'))).toEqual([])
  expect(requests.some(url => url.includes('local-case-assets'))).toBe(false)
  expect(errors).toEqual([])
  await mkdir('artifacts/runtime/beta-demo', { recursive: true })
  await page.close()
  await page.video()!.saveAs('artifacts/runtime/beta-demo/offline-demo.webm')
})

test('cancelling and switching cannot retain approved stale reports; missing optional media keeps Mock available', async ({ page }) => {
  await page.goto(demo)
  await page.locator('#run').click()
  await expect(page.locator('#progress')).toHaveAttribute('value', '1')
  await page.locator('#run').click()
  await expect(page.locator('#status')).toContainText('未生成完成记录')
  await expect(page.locator('#history li')).toHaveCount(0)
  await page.locator('#run').click()
  await page.locator('#failure').click()
  await expect(page.locator('#progress')).toHaveAttribute('value', '0')
  await page.locator('#run').click()
  await expect(page.locator('#status')).toContainText('第 5 步未执行')
  await expect(page.locator('#history li')).toHaveCount(1)
  await page.locator('#preview-report').click()
  await page.locator('#report-confirm').check()
  await page.locator('#rerun').click()
  await expect(page.locator('#report-preview')).toBeHidden()
  await expect(page.locator('#download-report')).toBeDisabled()
  await expect(page.locator('#status')).toContainText('5 个模拟步骤完成')
  await expect(page.locator('#history li')).toHaveCount(2)
  await page.reload()
  await expect(page.locator('#history li')).toHaveCount(0)
  await expect(page.locator('#report-preview')).toBeHidden()
  await page.locator('#case-recorded').click()
  await expect(page.locator('#case-note')).toContainText('本机历史截图尚未导入')
  await expect(page.locator('#run')).toBeDisabled()
  await page.locator('#case-basic').click()
  await page.locator('#run').click()
  await expect(page.locator('#status')).toContainText('5 个模拟步骤完成')
})
