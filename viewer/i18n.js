export const TRANSLATIONS = Object.freeze({
  en: Object.freeze(en),
  'zh-CN': Object.freeze(zhCN),
})

export function normalizeLocale(value) {
  if (typeof value !== 'string') return null
  const normalized = value.trim().toLowerCase()
  if (normalized.startsWith('zh')) return 'zh-CN'
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  return null
}

export function readLocalePreference(storage) {
  if (!storage) return null
  try {
    const value = storage.getItem(LOCALE_STORAGE_KEY)
    if (SUPPORTED_LOCALES.includes(value)) return value
    if (value !== null && typeof storage.removeItem === 'function') storage.removeItem(LOCALE_STORAGE_KEY)
    return null
  } catch {
    return null
  }
}

export function writeLocalePreference(storage, locale) {
  if (!storage || !SUPPORTED_LOCALES.includes(locale)) return false
  try {
    storage.setItem(LOCALE_STORAGE_KEY, locale)
    return true
  } catch {
    return false
  }
}

export function resolveInitialLocale({ storage = null, languages = [] } = {}) {
  const saved = readLocalePreference(storage)
  if (saved) return saved
  const candidates = Array.isArray(languages) ? languages : [languages]
  return candidates.some((value) => normalizeLocale(value) === 'zh-CN') ? 'zh-CN' : 'en'
}

export function translate(locale, key, params = {}, catalogs = TRANSLATIONS) {
  const selected = locale === 'zh-CN' ? 'zh-CN' : 'en'
  const fallback = catalogs.en || TRANSLATIONS.en
  const selectedCatalog = catalogs[selected] || fallback
  const template = selectedCatalog[key] ?? fallback[key] ?? selectedCatalog['common.unavailable'] ?? fallback['common.unavailable'] ?? 'Unavailable'
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (_match, name) => String(params[name] ?? ''))
}

export function applyDocumentTranslations(document, locale) {
  const t = (key, params) => translate(locale, key, params)
  document.documentElement.lang = locale
  document.title = t('app.title')
  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.dataset.i18n)
  }
  for (const [attribute, dataAttribute] of [
    ['placeholder', 'i18nPlaceholder'],
    ['aria-label', 'i18nAriaLabel'],
    ['title', 'i18nTitle'],
    ['alt', 'i18nAlt'],
  ]) {
    for (const element of document.querySelectorAll(`[data-${dataAttribute.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}]`)) {
      element.setAttribute(attribute, t(element.dataset[dataAttribute]))
    }
  }
}
